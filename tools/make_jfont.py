#!/usr/bin/env python3
"""Builds src/jfont_data.c: the 8x8 Japanese glyphs Shelf draws with (the same set
Checkpoint uses).

Source: Fusion Pixel Font 8px monospaced, Japanese build (BDF), release 2026.11.10,
https://github.com/TakWolf/fusion-pixel-font (SIL Open Font License 1.1). Its Japanese
glyphs are the Misaki font by Num Kadoma.

Kept: every character of the Japanese standard sets (JIS X 0208 and the Windows
additions). Also written: a table that turns half-width kana into full-width kana and
accented Latin letters and curly punctuation into plain ASCII.

Usage: python3 tools/make_jfont.py fusion-pixel-8px-monospaced-ja.bdf src/jfont_data.c
"""
import sys, unicodedata, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bdf import parse

def wanted():
    s = set()
    for cp in range(0x80, 0x10000):
        if 0xD800 <= cp <= 0xDFFF: continue
        ch = chr(cp)
        for enc in ("euc_jp", "cp932"):
            try:
                e = ch.encode(enc)
                if len(e) == 2 and e[0] != 0x8E: s.add(cp)
            except UnicodeEncodeError: pass
    return s

def folds(have):
    f = {}
    for cp in range(0xFF61, 0xFFA0):
        t = unicodedata.normalize("NFKC", chr(cp))
        if len(t) == 1 and ord(t) in have: f[cp] = ord(t)
    for cp in list(range(0xA0, 0x250)) + list(range(0x1E00, 0x1F00)):
        if cp in have: continue
        t = "".join(c for c in unicodedata.normalize("NFKD", chr(cp)) if not unicodedata.combining(c))
        if len(t) == 1 and 0x20 <= ord(t) < 0x7F: f[cp] = ord(t)
    f.update({0xA0: 0x20, 0x2018: 0x27, 0x2019: 0x27, 0x201C: 0x22, 0x201D: 0x22, 0x2013: 0x2D, 0x2014: 0x2D,
              0x2212: 0x2D, 0xDF: 0x73, 0xC6: 0x41, 0xE6: 0x61, 0xD8: 0x4F, 0xF8: 0x6F, 0x152: 0x4F, 0x153: 0x6F,
              0x141: 0x4C, 0x142: 0x6C, 0x2022: 0x2A, 0x2122: 0x20, 0xA9: 0x63, 0xAE: 0x72})
    return {k: v for k, v in f.items() if k not in have or k in (0x2018, 0x2019, 0x201C, 0x201D)}

def cell(g, asc):
    dw, (w, h, xo, yo), rows = g
    out = [0] * 8
    top = asc - (yo + h)
    for r, (bits, nb) in enumerate(rows):
        y = top + r
        if not 0 <= y < 8: continue
        v = 0
        for c in range(w):
            if bits & (1 << (nb - 1 - c)) and 0 <= xo + c < 8: v |= 0x80 >> (xo + c)
        out[y] = v
    return out

def main(src, dst):
    glyphs, asc, desc = parse(src)
    keep = sorted(cp for cp in wanted() if cp in glyphs and glyphs[cp][0] == 8)
    have = set(keep)
    fold = folds(have)
    for k in list(fold):
        if k in have and fold[k] < 0x80: have.discard(k)
    keep = sorted(have)
    with open(dst, "w") as o:
        o.write("/* Generated by tools/make_jfont.py. Do not edit.\n"
                " * 8x8 glyphs from Fusion Pixel Font 8px (SIL Open Font License 1.1), whose Japanese\n"
                " * glyphs are the Misaki font by Num Kadoma. See LICENSE-FONT.txt. */\n\n")
        o.write("const int jfont_count = %d;\n" % len(keep))
        o.write("const unsigned short jfont_cp[%d] = {\n" % len(keep))
        for i in range(0, len(keep), 12): o.write("    " + ",".join("0x%04X" % c for c in keep[i:i + 12]) + ",\n")
        o.write("};\nconst unsigned char jfont_bits[%d] = {\n" % (len(keep) * 8))
        for cp in keep: o.write("    " + ",".join("0x%02X" % v for v in cell(glyphs[cp], asc)) + ",\n")
        fk = sorted(fold)
        o.write("};\nconst int jfont_fold_count = %d;\n" % len(fk))
        o.write("const unsigned short jfont_fold_from[%d] = {\n" % len(fk))
        for i in range(0, len(fk), 12): o.write("    " + ",".join("0x%04X" % c for c in fk[i:i + 12]) + ",\n")
        o.write("};\nconst unsigned short jfont_fold_to[%d] = {\n" % len(fk))
        for i in range(0, len(fk), 12): o.write("    " + ",".join("0x%04X" % fold[c] for c in fk[i:i + 12]) + ",\n")
        o.write("};\n")
    print(len(keep), "glyphs,", len(fk), "folds")

if __name__ == "__main__": main(sys.argv[1], sys.argv[2])
